package swea.d5.p7793;

import java.io.*;
import java.util.*;

public class Solution {

    static int N, M;
    static char[][] map;

    // 악마가 각 칸에 처음 도착하는 시간
    static int[][] devilTime;

    // 수연이가 각 칸에 처음 도착하는 시간
    static int[][] dist;

    static int[] dr = {-1, 1, 0, 0};
    static int[] dc = {0, 0, -1, 1};

    public static void main(String[] args) throws Exception {

        BufferedReader br = new BufferedReader(
                new InputStreamReader(System.in)
        );

        int T = Integer.parseInt(br.readLine().trim());

        for (int testCase = 1; testCase <= T; testCase++) {

            // 테스트케이스마다 N, M과 지도를 입력받음.
            StringTokenizer st = new StringTokenizer(br.readLine());

            N = Integer.parseInt(st.nextToken());
            M = Integer.parseInt(st.nextToken());

            map = new char[N][M];
            devilTime = new int[N][M];
            dist = new int[N][M];

            // -1 = 아직 도달하지 못한 곳
            for (int r = 0; r < N; r++) {
                Arrays.fill(devilTime[r], -1);
                Arrays.fill(dist[r], -1);
            }

            // =====================================================
            // [수도코드 2, 3]
            // S의 위치를 찾는다.
            // 모든 *의 위치를 악마 Queue에 넣는다.
            // =====================================================

            int sRow = -1;
            int sCol = -1;

            Queue<int[]> devilQueue = new ArrayDeque<>();

            for (int r = 0; r < N; r++) {

                String line = br.readLine();

                for (int c = 0; c < M; c++) {

                    map[r][c] = line.charAt(c);

                    // 악마 발견
                    if (map[r][c] == '*') {

                        // 모든 악마를 시작점으로 Queue에 넣는다.
                        devilQueue.offer(new int[]{r, c});

                        // 처음 악마가 있는 위치의 시간은 0초
                        devilTime[r][c] = 0;
                    }

                    // 수연이 시작 위치 발견
                    else if (map[r][c] == 'S') {
                        sRow = r;
                        sCol = c;
                    }
                }
            }

            // =====================================================
            // [수도코드 4 - 6]
            // 악마 BFS를 먼저 수행해서
            // 각 칸에 악마가 최초로 도착하는 시간을 구한다.
            // =====================================================

            bfsDevil(devilQueue);

            // =====================================================
            // [수도코드 7 - 11]
            // S에서 출발하여 수연이 BFS를 수행한다.
            // =====================================================

            int answer = bfsSuyeon(sRow, sCol);

            // =====================================================
            // [수도코드 12]
            // D에 도착하지 못했다면 GAME OVER
            // 도착했다면 최소 시간을 출력한다.
            // =====================================================

            if (answer == -1) {
                System.out.println("#" + testCase + " GAME OVER");
            } else {
                System.out.println("#" + testCase + " " + answer);
            }
        }
    }


    // =============================================================
    // 악마 BFS
    // =============================================================

    static void bfsDevil(Queue<int[]> queue) {

        // [수도코드 6]
        // Queue가 빌 때까지 반복한다.
        while (!queue.isEmpty()) {

            // -----------------------------------------------------
            // [수도코드 6-1]
            // Queue에서 악마 위치 하나를 꺼낸다.
            // -----------------------------------------------------

            int[] current = queue.poll();

            int row = current[0];
            int col = current[1];

            // -----------------------------------------------------
            // [수도코드 6-2]
            // 현재 위치의 상하좌우를 확인한다.
            // -----------------------------------------------------

            for (int i = 0; i < 4; i++) {

                int nr = row + dr[i];
                int nc = col + dc[i];

                // -------------------------------------------------
                // [수도코드 6-3]
                // 배열 범위를 벗어나면 갈 수 없다.
                // -------------------------------------------------

                if (nr < 0 || nr >= N || nc < 0 || nc >= M) {
                    continue;
                }

                // -------------------------------------------------
                // [수도코드 6-4]
                // X에는 악마가 퍼질 수 없다.
                // -------------------------------------------------

                if (map[nr][nc] == 'X') {
                    continue;
                }

                // -------------------------------------------------
                // [수도코드 6-5]
                // D는 악마가 침범할 수 없다.
                // -------------------------------------------------

                if (map[nr][nc] == 'D') {
                    continue;
                }

                // -------------------------------------------------
                // [수도코드 6-6]
                // 이미 악마가 방문한 곳이라면 다시 방문하지 않는다.
                //
                // devilTime != -1
                // = 이미 악마의 도착 시간이 기록되어 있음
                // -------------------------------------------------

                if (devilTime[nr][nc] != -1) {
                    continue;
                }

                // -------------------------------------------------
                // [수도코드 6-7]
                // 다음 칸의 악마 도착 시간
                // = 현재 칸의 시간 + 1초
                // -------------------------------------------------

                devilTime[nr][nc]
                        = devilTime[row][col] + 1;

                // -------------------------------------------------
                // [수도코드 6-8]
                // 앞으로 이 위치의 주변도 확인해야 하므로
                // Queue에 넣는다.
                // -------------------------------------------------

                queue.offer(new int[]{nr, nc});
            }
        }
    }


    // =============================================================
    // 수연이 BFS
    // =============================================================

    static int bfsSuyeon(int sRow, int sCol) {

        Queue<int[]> queue = new ArrayDeque<>();

        // ---------------------------------------------------------
        // [수도코드 8]
        // S를 Queue에 넣는다.
        // ---------------------------------------------------------

        queue.offer(new int[]{sRow, sCol});

        // ---------------------------------------------------------
        // [수도코드 9]
        // 시작 위치까지 걸린 시간은 0초
        // ---------------------------------------------------------

        dist[sRow][sCol] = 0;

        // ---------------------------------------------------------
        // [수도코드 11]
        // Queue가 빌 때까지 반복한다.
        // ---------------------------------------------------------

        while (!queue.isEmpty()) {

            // -----------------------------------------------------
            // [수도코드 11-1]
            // 아직 주변을 조사하지 않은 위치 하나를 꺼낸다.
            // -----------------------------------------------------

            int[] current = queue.poll();

            int row = current[0];
            int col = current[1];

            // -----------------------------------------------------
            // [수도코드 11-2]
            // 상하좌우를 확인한다.
            // -----------------------------------------------------

            for (int i = 0; i < 4; i++) {

                int nr = row + dr[i];
                int nc = col + dc[i];

                // -------------------------------------------------
                // [수도코드 11-3]
                // 배열 밖이면 이동할 수 없다.
                // -------------------------------------------------

                if (nr < 0 || nr >= N || nc < 0 || nc >= M) {
                    continue;
                }

                // -------------------------------------------------
                // [수도코드 11-4]
                // 돌 X에는 이동할 수 없다.
                // -------------------------------------------------

                if (map[nr][nc] == 'X') {
                    continue;
                }

                // 처음부터 악마가 있던 칸에도 갈 수 없다.
                if (map[nr][nc] == '*') {
                    continue;
                }

                // -------------------------------------------------
                // [수도코드 11-6]
                // 이미 수연이가 발견한 칸이면 다시 가지 않는다.
                //
                // dist != -1
                // = 이미 최소 도착 시간이 기록된 칸
                // -------------------------------------------------

                if (dist[nr][nc] != -1) {
                    continue;
                }

                // -------------------------------------------------
                // 현재 위치에서 한 칸 움직이므로
                // 다음 칸까지 걸리는 시간은 +1
                // -------------------------------------------------

                int nextTime = dist[row][col] + 1;

                // -------------------------------------------------
                // [수도코드 11-7]
                // D를 발견했다면 최소 시간이다.
                //
                // BFS는 가까운 거리부터 탐색하기 때문에
                // 처음 D를 발견한 시간이 최단 시간이다.
                // -------------------------------------------------

                if (map[nr][nc] == 'D') {
                    return nextTime;
                }

                // -------------------------------------------------
                // [수도코드 11-9, 11-10]
                //
                // 악마가 이 칸에 도착하지 못한다면
                // devilTime[nr][nc] == -1
                //
                // → 안전하게 이동 가능
                //
                // 악마가 도착할 수 있다면
                //
                // 수연이 도착시간 < 악마 도착시간
                //
                // 이어야 한다.
                //
                // 같아도 이동할 수 없다.
                // -------------------------------------------------

                if (devilTime[nr][nc] != -1
                        && nextTime >= devilTime[nr][nc]) {

                    continue;
                }

                // -------------------------------------------------
                // 모든 조건을 통과했다.
                //
                // 이 칸까지의 최소 시간을 기록한다.
                // -------------------------------------------------

                dist[nr][nc] = nextTime;

                // -------------------------------------------------
                // 앞으로 이 위치의 주변도 조사해야 하므로
                // Queue에 넣는다.
                // -------------------------------------------------

                queue.offer(new int[]{nr, nc});
            }
        }

        // ---------------------------------------------------------
        // Queue가 전부 비었는데도 D를 발견하지 못했다.
        // ---------------------------------------------------------

        return -1;
    }
}